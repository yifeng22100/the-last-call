"""Render docs/RESULTS.md from site/data/facts.json (no hand-typed numbers).

    python -m lastcall.report
"""
import json

from .data import ROOT

FACTS = ROOT / "site" / "data" / "facts.json"
OUT = ROOT / "docs" / "RESULTS.md"


def pct(v, nd=1):
    return f"{v * 100:.{nd}f}%"


def ci(c, nd=1):
    return f"[{c[0] * 100:.{nd}f}%, {c[1] * 100:.{nd}f}%]"


def pts(d):
    m = lambda v: f"{'−' if v < 0 else ''}{abs(v) * 100:.1f}"
    return f"{'+' if d['mean'] >= 0 else ''}{m(d['mean'])} pts [{m(d['ci'][0])}, {m(d['ci'][1])}]"


def main():
    f = json.loads(FACTS.read_text())
    ds, a, sel = f["dataset"], f["auc"], f["model_selection"]["selected"]
    L = ["# Results", "",
         "_Generated by `python -m lastcall.build && python -m lastcall.report` from `site/data/facts.json`. "
         "Every figure here is re-computed independently in `verify/` (see `verify/REPORT.md`)._", "",
         "## Data", "",
         f"- {ds['clients']:,} clients, {ds['total_calls']:,} calls, {ds['subscribed']:,} subscriptions "
         f"({pct(ds['conversion'], 2)}, 95% CI {ci(ds['conversion_ci'], 2)}), {ds['first_period']} to {ds['last_period']} "
         f"({ds['months_with_data']} months with calls).",
         f"- Raw file SHA-256 `{ds['sha256']}` (identical to the official UCI release).", ""]
    L += ["| Window | Months | Clients | Calls | Subscribed | Conversion |", "|---|---|---:|---:|---:|---:|"]
    for k, w in f["windows"].items():
        L.append(f"| {k.replace('_', ' ')} | {w['first']} to {w['last']} | {w['clients']:,} | {w['calls']:,} | "
                 f"{w['subscribed']:,} | {pct(w['conversion'])} |")

    L += ["", "## Finding 1: leakage and time", "",
          "Gradient boosting, identical settings, ROC AUC:", "",
          "| Setup | AUC |", "|---|---:|",
          f"| All 20 inputs, shuffled 5-fold CV | {a['typical_all_inputs_random_split']:.3f} |",
          f"| Without `duration`, shuffled | {a['without_duration_random_split']:.3f} |",
          f"| Pre-call inputs only, shuffled | {a['precall_random_split']:.3f} |",
          f"| Pre-call inputs only, walk-forward (pooled) | {a['precall_walk_forward_gradient_boosting']:.3f} |",
          f"| Pre-call inputs only, walk-forward (mean within month) | {a['precall_walk_forward_gradient_boosting_mean_within_month']:.3f} |",
          f"| Logistic regression, walk-forward (pooled) | {a['precall_walk_forward_logistic']:.3f} |", ""]
    fz = f["frozen_model"]
    L += [f"A gradient-boosting model frozen at the end of 2008 predicts {pct(fz['2009']['frozen_gradient_boosting'])} "
          f"for 2009 (actual {pct(fz['2009']['actual'])}) and {pct(fz['2010']['frozen_gradient_boosting'])} for 2010 "
          f"(actual {pct(fz['2010']['actual'])}). Conversion by chronological eighth of the file: "
          + ", ".join(pct(v) for v in f["drift"]["eighths_conversion"])
          + f" ({f['drift']['ratio_last_to_first_eighth']}× first to last).", ""]

    L += ["## Finding 2: success rate of each call", "",
          "| Call | Calls made | Yes | Rate | 95% CI (Wilson) | Cumulative share of all yeses |",
          "|---|---:|---:|---:|---|---:|"]
    for r in f["per_call"]:
        L.append(f"| {r['call']} | {r['calls_made']:,} | {r['yes']:,} | {pct(r['rate'], 2)} | {ci(r['ci'], 2)} | "
                 f"{pct(r['cum_share_of_yes'])} |")
    L += ["", f"Call 2 / call 1 success-rate ratio: {f['call2_vs_call1']}.", "",
          f"Adjusted odds ratios vs. call 1 ({f['glm']['formula']}):", "",
          "| Term | Odds ratio | 95% CI |", "|---|---:|---|"]
    for k, v in f["glm"]["odds_ratios"].items():
        if k != "Intercept":
            L.append(f"| `{k}` | {v['or_']:.3f} | [{v['ci'][0]:.3f}, {v['ci'][1]:.3f}] |")

    L += ["", "## Model selection (2009 validation only)", "",
          f"Rule: {f['model_selection']['rule']}. Selected: **{sel}**.", "",
          "| Candidate | Inputs | Yes kept @25% | @50% | @75% | AUC (next call) |", "|---|---|---:|---:|---:|---:|"]
    for k, v in f["model_selection"]["candidates"].items():
        y = v["yes_kept"]
        L.append(f"| {k} | {v['features']} | {pct(y['0.25'])} | {pct(y['0.5'])} | {pct(y['0.75'])} | {v['auc_next_call']:.3f} |")

    L += ["", "## Policies at half the calls", "",
          "Share of subscriptions kept when making 50% of the bank's calls; brackets are 95% cluster-bootstrap intervals.", "",
          "| Period | Next-call model | Client scoring (logistic) | Max-N-calls rule | Next-call − client scoring | Next-call − max-N |",
          "|---|---:|---:|---:|---:|---:|"]
    nc = {"validation": f["model_selection"]["candidates"][sel], "holdout": f["holdout"][sel], "out_of_sample": f["out_of_sample"][sel]}
    for w in ("validation", "holdout", "out_of_sample"):
        b, pdiff = f["baselines"][w], f["paired_differences"][w]["0.5"]
        n_ci = nc[w].get("yes_kept_ci", {}).get("0.5")
        L.append(f"| {w.replace('_', ' ')} | {pct(nc[w]['yes_kept']['0.5'])}{' ' + ci(n_ci) if n_ci else ''} | "
                 f"{pct(b['client_ranking_logistic']['yes_kept']['0.5'])} {ci(b['client_ranking_logistic']['yes_kept_ci']['0.5'])} | "
                 f"{pct(b['call_cap']['yes_kept']['0.5'])} | {pts(pdiff['next_call_minus_client_ranking'])} | "
                 f"{pts(pdiff['next_call_minus_call_cap'])} |")

    sg, rb = f["safeguards"], f["regime_break"]
    L += ["", "## Safeguards and the money rule", "",
          f"In {rb['period']} (first out-of-sample month, {rb['calls']:,} calls) the unguarded model gave "
          f"{pct(rb['share_predicted_below_1pct'], 0)} of calls a predicted chance below 1% (mean {pct(rb['mean_predicted_unguarded'], 2)}); "
          f"{pct(rb['observed_success_rate'])} succeeded. Safeguards: {sg['rule']}. "
          f"The rule was active for {pct(sg['active_share_of_calls'])} of out-of-sample calls.", "",
          "| Month | Status | Logit shift |", "|---|---|---:|"]
    for m, v in sg["months"].items():
        L.append(f"| {m} | {v['status']} | {'' if v['shift'] is None else v['shift']} |")
    L += ["", "Calibration of guarded predictions (active months, deciles):", "",
          "| Predicted | Observed | Calls |", "|---:|---:|---:|"]
    for d in f["calibration_guarded_deciles"]:
        L.append(f"| {pct(d['predicted'])} | {pct(d['observed'])} | {d['n']:,} |")
    L += ["", f"Money rule over the out-of-sample period ({f['money_rule']['note']}):", "",
          "| Value/cost | Threshold | Calls made | Yes kept | Success rate of cut calls | Gain (call costs) | Per 1,000 clients | Hindsight best |",
          "|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for k, v in f["money_rule"]["by_value_to_cost"].items():
        L.append(f"| {k} | {pct(v['threshold'])} | {v['calls_made']:,} ({pct(v['calls_share'])}) | {v['yes_kept']:,} "
                 f"({pct(v['yes_kept_share'])}) | {pct(v['cut_calls_success_rate'])} | {v['profit_gain_in_call_costs']:,.0f} | "
                 f"{v['profit_gain_per_1000_clients']:,.1f} | {v['hindsight_best_gain']:,.0f} @ {pct(v['hindsight_best_threshold'], 2)} |")

    er = f["example_rule"]
    L += ["", f"## Age groups at a {pct(er['threshold'], 0)} threshold", "",
          "| Age group | Clients | Subscribed | Subscriptions captured | Calls made | Clients contacted |",
          "|---|---:|---:|---:|---:|---:|"]
    for g, v in er["by_age"].items():
        L.append(f"| {g} | {v['clients']:,} | {v['subscribed']:,} | {pct(v['yes_kept_share'])} | {pct(v['calls_share'])} | "
                 f"{pct(v['contacted_share'])} |")
    L.append(f"| all | | | {pct(er['yes_kept'])} | {pct(er['calls_share'])} | |")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
